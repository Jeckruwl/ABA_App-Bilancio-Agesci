const assert = require('node:assert/strict');
require('../receipt-ocr.js');
const parse = globalThis.ReceiptOCR.parseReceipt;
let r = parse('SUPERMERCATO ROSSI\nVia Roma 1\nDOCUMENTO COMMERCIALE\nData 12/11/2026 15:42\nSUBTOTALE 14,00\nTOTALE COMPLESSIVO EUR 12,50\nCONTANTI 20,00\nRESTO 7,50');
assert.equal(r.date, '2026-11-12'); assert.equal(r.amount,'12.50'); assert.equal(r.description,'Scontrino - SUPERMERCATO ROSSI');
r=parse('NEGOZIO ALFA\nDATA 01-02-26\nDATA 02-02-26\nTOTALE 5,00\nTOTALE 6,00');
assert.equal(r.date,null); assert.equal(r.amount,null); assert(r.ambiguousDate && r.ambiguousAmount);
r=parse('ESERCIZIO BETA\n31/02/2026\nSUBTOTALE 9,00\nTOTALE IVA 2,00\nPAGAMENTO 11,00');
assert.equal(r.date,null); assert.equal(r.amount,null);
r=parse('TOTALE\n1.234,56'); assert.equal(r.amount,'1234.56');
r=parse('TOTALE -12,00'); assert.equal(r.amount,null);
console.log('Analisi scontrino: date, totali, conflitti e righe da ignorare OK');
